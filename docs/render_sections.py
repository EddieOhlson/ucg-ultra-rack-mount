import trimesh, matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
a=trimesh.load("out/assembly_preview.stl")
fig,axs=plt.subplots(3,1,figsize=(14,9),gridspec_kw={'height_ratios':[1,1.6,1]})
s=a.section(plane_origin=[0,0.3,0],plane_normal=[0,1,0])
for e in s.discrete: axs[0].plot(e[:,0],e[:,2],'k',lw=.5)
axs[0].set_aspect('equal');axs[0].set_title('Front face')
s=a.section(plane_origin=[0,0,1.5],plane_normal=[0,0,1])
for e in s.discrete: axs[1].plot(e[:,0],e[:,1],'k',lw=.6)
axs[1].set_aspect('equal');axs[1].invert_yaxis();axs[1].set_title('Floor plan (z=1.5)')
s=a.section(plane_origin=[155,0,0],plane_normal=[1,0,0])
for e in s.discrete: axs[2].plot(e[:,1],e[:,2],'k',lw=.6)
g=trimesh.load("out/gateway_ghost.stl").section(plane_origin=[155,0,0],plane_normal=[1,0,0])
for e in g.discrete: axs[2].plot(e[:,1],e[:,2],'b--',lw=.6)
axs[2].set_aspect('equal');axs[2].set_title('Side section through gateway (blue = UCG-Ultra)')
plt.tight_layout();plt.savefig("out/sections.png",dpi=110)
